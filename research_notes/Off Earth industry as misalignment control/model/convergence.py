"""
Convergence of the pact ensembles in grid size nA, horizon T_H and ensemble size (issue #71).

    python3 convergence.py --solve --runs-dir DIR   # solve every setting into DIR (never into results/robust_runs)
    python3 convergence.py --report --runs-dir DIR  # results/convergence.md and results/convergence.json

The committed resolution is nA = 160, T_H = 300 (robust_design.CFG) on the r0.1 box (64 draws, seed 105). Each other
setting re-solves the same draws with one numerical setting changed (plus one corner with both raised); the ensemble-size
rows draw fresh, larger Latin hypercubes from the same box. Every cache carries a run_identity manifest.

'holds' depends on the horizon: P(strike) is counted up to T_H. 'holds100' (cooperate at t = 0 and P(strike within 100
years) < 1%) is the same predicate at every T_H, so it is the fair horizon comparison.
Status: implemented. Not human_validated.
"""
from __future__ import annotations

import argparse
import json
import os
import time
from concurrent.futures import ProcessPoolExecutor

os.environ.setdefault("OMP_NUM_THREADS", "1")
import numpy as np

import robust_design as rd
import run_identity as ri

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")
WORKERS = int(os.environ.get("CV_WORKERS", "4"))

BEST = dict(D_mult=3.0, T_reloc=4.0, d=0.99, q_red=2.0, seq=1)
DESIGNS = {"base": {}, "best": BEST}
REF = (160, 300)
# (nA, T_H): one setting at a time, plus the corner with both raised
RESOLUTIONS = [REF, (120, 300), (240, 300), (320, 300), (160, 200), (160, 450), (160, 600), (320, 600)]
SIZES = [128, 256]          # fresh r0.1 Latin hypercubes at the committed resolution (seed 105, as the 64-draw one)
SEED = 105


def draws(n=rd.N_RAD):
    return rd.ensemble("r0.1", n, seed=SEED)[1]


def ens_name(n):
    return "r0.1" if n == rd.N_RAD else f"r0.1n{n}"


def kw_for(nA, T_H):
    kw = {}
    if nA != rd.CFG["nA"]:
        kw["nA"] = nA
    if T_H != rd.CFG["T_H"]:
        kw["T_H"] = T_H
    return kw


def solve_all(pool):
    th = draws()
    for nA, T_H in RESOLUTIONS:
        for des, dv in DESIGNS.items():
            t0 = time.time()
            rd.run_design("r0.1", th, dv, pool, **kw_for(nA, T_H))
            print(f"[convergence] nA {nA} T_H {T_H} {des}: {time.time() - t0:.0f} s", flush=True)
    for n in SIZES:
        thn = draws(n)
        for des, dv in DESIGNS.items():
            t0 = time.time()
            rd.run_design(ens_name(n), thn, dv, pool)
            print(f"[convergence] n {n} {des}: {time.time() - t0:.0f} s", flush=True)


def holds100(r):
    return np.isin(r["act0"], ["C", "P"]) & (r["att100"] < rd.STRIKE_TOL)


def load(ens, design, **kw):
    path = os.path.join(rd.RUNS, rd.run_tag(ens, design, **kw) + ".npz")
    return ri.load_for_read(path), path


def wilson(k, n):
    lo, hi = rd.ci(k / n, n)
    return f"{k}/{n} ({lo:.2f}-{hi:.2f})"


def report(committed_dir):
    th = draws()
    out, L = {"resolution": [], "sizes": [], "reproduction": []}, []
    L.append("# Convergence in nA, T_H and ensemble size (auto-generated by convergence.py --report)\n")
    L.append(f"Issue #71. r0.1 box, {rd.N_RAD} draws (seed {SEED}), baseline design and best stack "
             "(D_mult 3, T_reloc 4 with seq b, d 0.99, q_red 2). Reference: nA 160, T_H 300, re-solved into the "
             "experiment folder. Hold shares are sampling-measure outcomes, not probabilities; intervals are Wilson 90%.\n")
    # reproduction of the committed caches at the reference resolution
    rows = []
    for des, dv in DESIGNS.items():
        new, _ = load("r0.1", dv)
        old = ri.load_for_read(os.path.join(committed_dir, rd.run_tag("r0.1", dv) + ".npz"))
        d = max(float(np.nanmax(np.abs(new[k] - old[k]))) for k in rd.KEEP if k in old)
        same = bool(np.all(new["act0"] == old["act0"])) and bool(np.all(rd.holds(new) == rd.holds(old)))
        rows.append([des, f"{d:.3g}", same])
        out["reproduction"].append(dict(design=des, maxdiff=d, same_outcomes=same))
    L.append("## 1. Reference re-solve against the committed cache (results/robust_runs)\n")
    L.append(rd.md_table(rows, ["design", "largest abs. difference (kept fields)", "act0 and holds identical"]) + "\n")
    # resolution
    L.append("## 2. Grid size and horizon (same 64 draws)\n")
    L.append("Flips are counted against the reference draw by draw. 'holds' counts strikes up to T_H, so it is "
             "not the same predicate across T_H; 'holds100' (strikes within 100 years) is. Values: WH is human "
             "welfare at t = 0; att is P(strike within T_H).\n")
    rows = []
    for des, dv in DESIGNS.items():
        ref, _ = load("r0.1", dv)
        for nA, T_H in RESOLUTIONS:
            r, _ = load("r0.1", dv, **kw_for(nA, T_H))
            h, h0 = rd.holds(r), rd.holds(ref)
            g, g0 = holds100(r), holds100(ref)
            fl = int(np.sum(h != h0))
            fl100 = int(np.sum(g != g0))
            a0 = int(np.sum(r["act0"] != ref["act0"]))
            dWH = np.abs(r["WH"] - ref["WH"])
            rel = dWH / np.maximum(np.abs(ref["WH"]), 1e-12)
            datt = np.abs(r["att"] - ref["att"])
            datt100 = np.abs(r["att100"] - ref["att100"])
            row = dict(design=des, nA=nA, T_H=T_H, holds=int(h.sum()), holds100=int(g.sum()), flips=fl,
                       gained=int(np.sum(h & ~h0)), lost=int(np.sum(h0 & ~h)), flips100=fl100, act0_changes=a0,
                       max_dWH=float(dWH.max()), max_rel_dWH=float(rel.max()), median_rel_dWH=float(np.median(rel)),
                       max_datt=float(datt.max()), max_datt100=float(datt100.max()),
                       flipped_draws=np.flatnonzero(h != h0).tolist(),
                       flipped_att=[[float(ref["att"][i]), float(r["att"][i])] for i in np.flatnonzero(h != h0)])
            out["resolution"].append(row)
            rows.append([des, nA, T_H, wilson(row["holds"], rd.N_RAD), row["holds100"], f"{fl} (+{row['gained']}/-{row['lost']})",
                         fl100, a0, f"{row['max_rel_dWH']:.2g}", f"{row['median_rel_dWH']:.2g}", f"{row['max_datt']:.3f}",
                         f"{row['max_datt100']:.3f}"])
    L.append(rd.md_table(rows, ["design", "nA", "T_H", "holds (90% CI)", "holds100", "hold flips (+gained/-lost)",
                                "holds100 flips", "act0 changes", "max rel. ΔWH", "median rel. ΔWH", "max Δatt",
                                "max Δatt100"]) + "\n")
    flips = [r for r in out["resolution"] if r["flips"]]
    if flips:
        L.append("Flipped draws (index: P(strike) at reference -> at this setting):\n")
        for r in flips:
            L.append(f"- {r['design']} nA {r['nA']} T_H {r['T_H']}: " + ", ".join(
                f"{i}: {a:.4f} -> {b:.4f}" for i, (a, b) in zip(r["flipped_draws"], r["flipped_att"])))
        L.append("")
    # ensemble size
    L.append("## 3. Ensemble size (fresh draws at the committed resolution)\n")
    rows = []
    for des, dv in DESIGNS.items():
        for n in [rd.N_RAD] + SIZES:
            r, _ = load(ens_name(n), dv)
            k = int(rd.holds(r).sum())
            kr = int((rd.holds(r) & (r["riv"] < 0.5)).sum())
            lo, hi = rd.ci(k / n, n)
            out["sizes"].append(dict(design=des, n=n, holds=k, share=k / n, ci90=[lo, hi], holds_rival=kr))
            rows.append([des, n, wilson(k, n), f"{k / n:.3f}", wilson(kr, n)])
    L.append(rd.md_table(rows, ["design", "draws", "holds (90% CI)", "share", "holds & P(rival) < 0.5"]) + "\n")
    leg = ri.legacy_read_summary()
    if leg:
        L.append(f"Reading note: {leg}.\n")
    open(os.path.join(RES, "convergence.md"), "w").write("\n".join(L) + "\n")
    json.dump(out, open(os.path.join(RES, "convergence.json"), "w"), indent=1)
    print("\n".join(L))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--solve", action="store_true")
    ap.add_argument("--report", action="store_true")
    ap.add_argument("--runs-dir", required=True, help="cache folder; must not be results/robust_runs")
    a = ap.parse_args()
    committed = rd.RUNS
    rd.RUNS = os.path.abspath(a.runs_dir)
    if os.path.samefile(rd.RUNS, committed) if os.path.exists(rd.RUNS) else False:
        raise SystemExit("convergence.py: --runs-dir must not be the committed cache folder")
    os.makedirs(rd.RUNS, exist_ok=True)
    if a.solve:
        with ProcessPoolExecutor(WORKERS) as pool:
            solve_all(pool)
    if a.report:
        report(committed)


if __name__ == "__main__":
    main()
