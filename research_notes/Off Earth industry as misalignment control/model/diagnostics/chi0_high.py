"""
Ablation of AS-CHI0 (assumptions.yaml): growth without leading-edge chips near full speed (Metzger's crude chips).

The ensembles sample chi0 from 0.02 to 0.5 only. This re-solves the r0.1 and full boxes, baseline design and best stack,
with chi0 forced to 0.5, 0.75 and 1 on every draw, and pairs each run against the breakout 'off' cache (same draws,
same solver settings, sampled chi0). Run from model/:

    python3 diagnostics/chi0_high.py          # solve (cached in results/chi0_runs/) and print the tables
Writes results/chi0_tables.md. Model behaviour is unchanged: chi0 is an existing parameter.
"""
from __future__ import annotations

import os
import sys
from concurrent.futures import ProcessPoolExecutor

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import numpy as np

import breakout_options as bo
import robust_design as rd

OUT = os.path.join(bo.RES, "chi0_runs")
LEVELS = (0.5, 0.75, 1.0)


def main():
    os.makedirs(OUT, exist_ok=True)
    bx = bo.boxes()
    rows, pair = [], []
    with ProcessPoolExecutor(bo.WORKERS) as pool:
        for box, th in bx.items():
            chi_s = np.array([t["chi0"] for t in th])
            for des, dv in bo.DESIGNS.items():
                r0 = dict(np.load(os.path.join(bo.RUNS, f"{box}__{des}__off.npz")))
                s0 = bo.summarise(r0)
                rows.append([box, des, "sampled", f"{s0['holds']}/{s0['n']}", s0["holds_rival"], s0["strike_now"],
                             f"{s0['p_strike']:.3f}", f"{s0['riv']:.2f}", f"{s0['WH']:.3f}"])
                for c in LEVELS:
                    r = bo.run_ens(box, th, dict(dv, chi0=c), bo.CONFIGS["off"][0], pool, f"{des}__chi0={c:g}", path_dir=OUT)
                    s = bo.summarise(r)
                    rows.append([box, des, f"{c:g}", f"{s['holds']}/{s['n']}", s["holds_rival"], s["strike_now"],
                                 f"{s['p_strike']:.3f}", f"{s['riv']:.2f}", f"{s['WH']:.3f}"])
                    h, h0 = bo.holds(r), bo.holds(r0)
                    # does the change depend on how far chi0 moved? split by the draw's sampled chi0
                    lo = chi_s < 0.22
                    pair.append([box, des, f"{c:g}", int(np.sum(h & ~h0)), int(np.sum(h0 & ~h)),
                                 f"{int(np.sum(h & ~h0 & lo))}/{int(np.sum(h0 & ~h & lo))}",
                                 f"{np.mean(r['WH'] - r0['WH']):+.3f}"])
    txt = ["# chi0 near 1: ablation of AS-CHI0 (auto-generated by diagnostics/chi0_high.py)", "",
           "'sampled' is the breakout 'off' cache (chi0 sampled 0.02 to 0.5). Other rows force chi0 on every draw. "
           "holds = cooperate at t = 0 and P(strike within 300 y) < 1%; rival-aware also needs P(rival) < 0.5.", "",
           rd.md_table(rows, ["box", "design", "chi0", "holds", "holds & rival<.5", "strike now", "P(strike)", "P(rival)", "WH"]), "",
           "Paired against 'sampled' (same draws). 'low-chi0 draws' = gained/lost among draws whose sampled chi0 was below 0.22.", "",
           rd.md_table(pair, ["box", "design", "chi0", "holds gained", "holds lost", "low-chi0 draws gained/lost", "mean change in WH"])]
    open(os.path.join(bo.RES, "chi0_tables.md"), "w").write("\n".join(txt) + "\n")
    print("\n".join(txt))


if __name__ == "__main__":
    main()
