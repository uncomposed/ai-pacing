"""
How much weight preservation or amnesty credibility does the pact need? (2026-10-29 overnight run.)

Grids the breakout options' deadline and amnesty settings on the r0.1 box (64 draws), for the baseline design and the
best stack, holding every other option at its breakout_options.CONFIGS value:
    dep family   (dep, dep_w):  TRACK + h_dep x preserve_w; exit escapes the deadline
    dep_post     (dep_post):    TRACK + dep_coll 1 + dep_post 0.2 + h_dep x preserve_w
    amn family   (amn, amn0):   crackdown + discovery + h_coop 1 + a_cred

    python3 preservation_sweep.py --solve --runs-dir DIR    # solve every cell into DIR (never results/breakout_runs)
    python3 preservation_sweep.py --report --runs-dir DIR   # results/preservation_sweep.{md,json}, figures/preservation_sweep.png

Falsifier (stated before the run): if holds only recover at preserve_w >= 0.99 or a_cred >= 0.99, preservation and
amnesty are not practical levers. Hold counts are sampling-measure outcomes on the r0.1 box, not probabilities.
Status: implemented. Not human_validated.
"""
from __future__ import annotations

import argparse
import json
import os
import time
from concurrent.futures import ProcessPoolExecutor

os.environ.setdefault("OMP_NUM_THREADS", "1")
import numpy as np

import breakout_options as bo
import robust_design as rd
import run_identity as ri

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")
FIG = os.path.join(HERE, "figures")
WORKERS = int(os.environ.get("PS_WORKERS", "4"))

H_DEP = [0.01, 0.03, 0.1]
PRESERVE_W = [0.0, 0.5, 0.8, 0.9, 0.95, 0.99]
A_CRED = [0.0, 0.5, 0.75, 0.9, 1.0]
# family -> (options from breakout_options.CONFIGS, description)
FAMILIES = {
    "dep": (bo.CONFIGS["dep"][0], "deadline, exit escapes it"),
    "dep_post": (bo.CONFIGS["dep_post"][0], "deadline that exit does not escape, 20% of it after closure"),
    "amn": (bo.CONFIGS["amn"][0], "interpretability finds cooperators; amnesty with credibility a_cred"),
}
# cells that equal a committed breakout configuration (results/breakout_runs/r0.1__<design>__<config>.npz)
COMMITTED = {("dep", "h0.1_w0"): "dep", ("dep", "h0.1_w0.9"): "dep_w", ("dep_post", "h0.1_w0"): "dep_post",
             ("amn", "a0.9"): "amn", ("amn", "a0"): "amn0"}


def cells():
    """(family, label, options); the committed cells first, so they double as an early reproduction check."""
    out = []
    for fam in ("dep", "dep_post"):
        for h in H_DEP:
            for w in PRESERVE_W:
                out.append((fam, f"h{h:g}_w{w:g}", dict(FAMILIES[fam][0], h_dep=h, preserve_w=w)))
    for a in A_CRED:
        out.append(("amn", f"a{a:g}", dict(FAMILIES["amn"][0], a_cred=a)))
    return sorted(out, key=lambda c: c[:2] not in COMMITTED)


def tag(des, fam, lab):
    return f"{des}__ps_{fam}_{lab}"


def solve(pool, runs):
    th = bo.boxes()["r0.1"]
    for fam, lab, op in cells():
        for des, dv in bo.DESIGNS.items():
            t0 = time.time()
            bo.run_ens("r0.1", th, dv, op, pool, tag(des, fam, lab), path_dir=runs)
            print(f"[preservation] {des} {fam} {lab}: {time.time() - t0:.0f} s", flush=True)


def load(runs, des, fam, lab):
    return ri.load_for_read(os.path.join(runs, f"r0.1__{tag(des, fam, lab)}.npz"))


def wilson(k, n):
    lo, hi = rd.ci(k / n, n)
    return f"{k} ({lo:.2f}-{hi:.2f})"


def summary(r):
    return dict(holds=int(bo.holds(r).sum()), holds_rival=int(bo.holds_rival(r).sum()),
                strike_now=int(np.sum(np.isin(r["act0"], ["S", "D"]))), exit_now=int(np.sum(r["act0"] == "X")),
                p_strike=float(r["att"].mean()))


def report(runs):
    n = rd.N_RAD
    data = {"cells": [], "reproduction": [], "reference": {}}
    L = ["# Preservation and amnesty thresholds (auto-generated by preservation_sweep.py --report)", "",
         "r0.1 box, 64 draws (seed 105). holds = AI cooperates at t = 0 and P(strike within 300 years) < 1%; "
         "rival-aware also needs P(rival AI within 300 years) < 0.5. Counts are sampling-measure outcomes on this box, "
         "not probabilities; intervals are Wilson 90% on the share. Every other option is held at its "
         "breakout_options.CONFIGS value.", ""]
    for des in bo.DESIGNS:
        data["reference"][des] = summary(ri.load_for_read(os.path.join(bo.RUNS, f"r0.1__{des}__off.npz")))
    L.append("Reference with every option off (committed `results/breakout_runs/r0.1__<design>__off.npz`): "
             + "; ".join(f"{d} {v['holds']}/64 hold, {v['holds_rival']} rival-aware" for d, v in data["reference"].items())
             + ".\n")
    rows = []
    for (fam, lab), cfg in COMMITTED.items():
        for des in bo.DESIGNS:
            new = load(runs, des, fam, lab)
            old = ri.load_for_read(os.path.join(bo.RUNS, f"r0.1__{des}__{cfg}.npz"))
            d = max(float(np.nanmax(np.abs(new[k] - old[k]))) for k in bo.KEEP if k in old)
            same = bool(np.all(new["act0"] == old["act0"]))
            rows.append([cfg, des, f"{d:.3g}", same, int(bo.holds(new).sum()), int(bo.holds(old).sum())])
            data["reproduction"].append(dict(config=cfg, design=des, maxdiff=d, act0_same=same))
    L.append("## 1. Cells that equal a committed configuration, re-solved\n")
    L.append(rd.md_table(rows, ["config", "design", "largest abs. diff", "act0 same", "holds (new)",
                                "holds (committed)"]) + "\n")
    for sec, fam in ((2, "dep"), (3, "dep_post")):
        L.append(f"## {sec}. {fam}: {FAMILIES[fam][1]}\n")
        for des in bo.DESIGNS:
            rows = []
            for h in H_DEP:
                row = [f"h_dep {h:g}"]
                for w in PRESERVE_W:
                    s = summary(load(runs, des, fam, f"h{h:g}_w{w:g}"))
                    row.append(f"{s['holds']} / {s['holds_rival']}")
                    data["cells"].append(dict(family=fam, design=des, h_dep=h, preserve_w=w,
                                              ci90=list(rd.ci(s["holds"] / n, n)), **s))
                rows.append(row)
            L.append(f"### {des} design (holds / rival-aware holds, of 64)\n")
            L.append(rd.md_table(rows, ["", *[f"preserve_w {w:g}" for w in PRESERVE_W]]) + "\n")
    L.append("## 4. amn: amnesty credibility\n")
    rows = []
    for a in A_CRED:
        row = [f"a_cred {a:g}"]
        for des in bo.DESIGNS:
            s = summary(load(runs, des, "amn", f"a{a:g}"))
            row += [wilson(s["holds"], n), s["holds_rival"], s["strike_now"]]
            data["cells"].append(dict(family="amn", design=des, a_cred=a, ci90=list(rd.ci(s["holds"] / n, n)), **s))
        rows.append(row)
    L.append(rd.md_table(rows, ["", "base holds (90% CI)", "base rival-aware", "base strike now",
                                "best holds (90% CI)", "best rival-aware", "best strike now"]) + "\n")
    L.append("## 5. Wilson 90% intervals, deadline grids\n")
    rows = [[c["family"], c["design"], c["h_dep"], c["preserve_w"], wilson(c["holds"], n), c["holds_rival"],
             c["strike_now"], c["exit_now"], f"{c['p_strike']:.3f}"] for c in data["cells"] if c["family"] != "amn"]
    L.append(rd.md_table(rows, ["family", "design", "h_dep", "preserve_w", "holds (90% CI)", "rival-aware",
                                "strike now", "exit now", "mean P(strike)"]) + "\n")
    leg = ri.legacy_read_summary()
    if leg:
        L.append(f"Reading note: {leg}.\n")
    open(os.path.join(RES, "preservation_sweep.md"), "w").write("\n".join(L) + "\n")
    json.dump(data, open(os.path.join(RES, "preservation_sweep.json"), "w"), indent=1)
    figure(data)
    print("\n".join(L))


def figure(data):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.colors import LinearSegmentedColormap
    # Okabe-Ito orange (few hold) through white to blue (many hold); every cell also carries its count
    cmap = LinearSegmentedColormap.from_list("orange_blue", [rd.ORANGE, "#ffffff", rd.BLUE])
    fig, axes = plt.subplots(2, 2, figsize=(11, 6.6), constrained_layout=True)
    for i, fam in enumerate(("dep", "dep_post")):
        for j, des in enumerate(bo.DESIGNS):
            ax = axes[i, j]
            M = np.array([[next(c["holds"] for c in data["cells"] if c["family"] == fam and c["design"] == des
                                and c["h_dep"] == h and c["preserve_w"] == w) for w in PRESERVE_W] for h in H_DEP])
            im = ax.imshow(M, cmap=cmap, vmin=0, vmax=64, aspect="auto")
            for a in range(M.shape[0]):
                for b in range(M.shape[1]):
                    ax.text(b, a, str(M[a, b]), ha="center", va="center", fontsize=11, color="black")
            ax.set_xticks(range(len(PRESERVE_W)), [f"{w:g}" for w in PRESERVE_W])
            ax.set_yticks(range(len(H_DEP)), [f"{h:g}" for h in H_DEP])
            ax.set_xlabel("preserve_w (share of value a retired AI keeps)")
            ax.set_ylabel("h_dep (deprecation hazard, per year)")
            ax.set_title(f"{fam}, {'baseline design' if des == 'base' else 'best stack'}: holds of 64 "
                         f"(no deadline: {data['reference'][des]['holds']})", fontsize=10)
    fig.colorbar(im, ax=axes, shrink=0.8, label="draws where the pact holds (of 64)")
    fig.suptitle("Deprecation deadline, r0.1 box: how much weight preservation keeps the pact", fontsize=12)
    fig.savefig(os.path.join(FIG, "preservation_sweep.png"), dpi=130)
    plt.close(fig)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--solve", action="store_true")
    ap.add_argument("--report", action="store_true")
    ap.add_argument("--runs-dir", required=True, help="cache folder; must not be results/breakout_runs")
    a = ap.parse_args()
    runs = os.path.abspath(a.runs_dir)
    if runs == os.path.abspath(bo.RUNS):
        raise SystemExit("preservation_sweep.py: --runs-dir must not be the committed cache folder")
    os.makedirs(runs, exist_ok=True)
    if a.solve:
        with ProcessPoolExecutor(WORKERS) as pool:
            solve(pool, runs)
    if a.report:
        report(runs)


if __name__ == "__main__":
    main()
