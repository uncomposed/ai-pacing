def _read_json(path):
    with open(path) as f:
        return json.load(f)


fmt = C.fmt


def stage_bargaining() -> dict:
    raw = bg.run_all()
    table = {}
    for s, R in raw.items():
        p, _ = bg.scenario(s)
        table[s] = {r: rk.measures_bargaining(o, p["w_seized"]) for r, o in R.items() if r != "diagnostics"}
    return dict(raw=raw, measures=table, analysis=rk.analyse(table, "fixed"))


def stage_preventive() -> dict:
    raw = pv.run_all()
    base = em.baseline(**pv.R6_CLEAN)
    table = {s: {p: rk.measures_preventive(o, dict(base, **pv.STRUCTURES[s])["w_seized"]) for p, o in R.items()}
             for s, R in raw.items()}
    checks = baseline_checks()
    return dict(raw=raw, measures=table, analysis=rk.analyse(table, "none"), checks=checks,
                structures=pv.STRUCTURES, policies=pv.POLICIES)


# The reduced game's baseline limit against the full solver (results/equilibrium_round3_summary.json, R6c, mu = 0)
# and against the saturation closed form em.q_star_cap / em.cap_gap_fail.
R6C_CELLS = [(0.003, 0.5), (0.1, 0.1), (0.1, 0.5), (1.0, 0.5), (0.03, 0.9)]


def baseline_checks() -> dict:
    ref = _read_json((os.path.join(C.MODEL, "results", "equilibrium_round3_summary.json")))["r6_solver"]
    solver = {tuple(c): tuple(b) for c, b in zip(ref["clean_cases"], ref["q_clean"])}
    base = em.baseline(**pv.R6_CLEAN)
    rows = []
    for ac, lf in R6C_CELLS:
        p = dict(base, A0=ac, A_close=ac, L_f=lf, d=1.0, w_seized=0.9)
        rows.append(dict(A_close=ac, L_f=lf, rbg=pv.needed_q(p), solver=solver[(ac, lf)]))
    cap = []
    for A0 in (1e9 * 1.000001, 1.5e9):
        p = dict(base, A0=A0, d=1.0, w_seized=0.9)
        # closed-form threshold at this size: bisection on cap_gap_fail
        lo, hi = 0.0, 1.0
        for _ in range(40):
            mid = 0.5 * (lo + hi)
            lo, hi = (mid, hi) if em.cap_gap_fail(dict(p, q=mid), A0) > 0 else (lo, mid)
        cap.append(dict(A0=A0, rbg=pv.needed_q(p, steps=10, T=150), closed_form=hi))
    return dict(r6c=rows, saturation=cap)


def stage_selection() -> dict:
    """AS-SELECTION: the full solver's own 'worst' stage-equilibrium selection on the 25 named scenarios."""
    import numpy as np
    import run_equilibrium as re_
    ps = em.batch([em.baseline(**o) for _, o in re_.SCEN])
    out = {}
    for sel in ("best", "worst"):
        r = em.solve(ps, N=2, T_H=300, nA=160, sel=sel)
        out[sel] = {k: [str(x) for x in r["act0"]] if k == "act0" else np.asarray(r[k], float).tolist()
                    for k in ("act0", "att", "suc", "riv", "WH", "t_mean")}
    out["names"] = [n for n, _ in re_.SCEN]
    out["flipped"] = [n for i, n in enumerate(out["names"]) if out["best"]["act0"][i] != out["worst"]["act0"][i]
                      or (out["best"]["att"][i] >= 0.5) != (out["worst"]["att"][i] >= 0.5)]
    return out


