def _load(name):
    path = os.path.join(C.OUT, name + ".json")
    return _read_json((path)) if os.path.exists(path) else None


def render() -> str:
    L = ["# Issue #9 variant tables", "",
         "[[ai gen]] Generated by `variants/run_variants.py tables` from `results/variants/*.json`. Do not edit by hand.",
         "Read with `results/variants.md`. Reduced models, not the full solver; no empirical validation.", ""]
    B = _load("bargaining")
    if B:
        L += ["## B1. Bargaining diagnostics (saturation, per year; x_max = H (1 + gam), x_lo = 0)", ""]
        rows = []
        for s, R in B["raw"].items():
            d = R["diagnostics"]
            rows.append([s, fmt(d["lockin_t0"]), fmt(d["lockin_max"]), fmt(d["surplus_t0"]), fmt(d["min_surplus"]),
                         fmt(d["bargain_exists_every_year"]), fmt(d["gap_max"]), fmt(d["commitment_problem"]),
                         fmt(d["first_gap_year"])])
        L += [C.md_table(rows, ["scenario", "AI lock-in t0", "max lock-in", "surplus t0", "min surplus",
                                "bargain exists every year", "max commitment gap", "commitment problem",
                                "first gap year"]), ""]
        L += ["## B2. Outcomes by regime (each measure separately)", ""]
        rows = []
        for s, R in B["raw"].items():
            for r, o in R.items():
                if r == "diagnostics":
                    continue
                m = B["measures"][s][r]
                rows.append([s, r, fmt(m["conflict_year"]), fmt(o["P_seizure"]), fmt(m["successful_harm"]),
                             fmt(m["control_retained"]), fmt(m["V_H"], 4), fmt(o["V_A"], 4), fmt(o["pv_transfer_H"]),
                             fmt(o["x_first"]), fmt(o["x_last"]), fmt(o["human_chose_war"])])
        L += [C.md_table(rows, ["scenario", "regime", "strike year", "P(seizure)", "successful harm",
                                "control retained", "human welfare", "AI value (net of own output)",
                                "PV paid by humans", "x first year", "x last year", "humans chose war"]), ""]
        L += _analysis_md("B3", B["analysis"])
    P = _load("preventive")
    if P:
        L += ["## H1. Reduced game, baseline limit against the full solver (needed q at d = 1, w_seized 0.9, mu = 0)",
              "", "Brackets are [strikes, does not strike] after 8 bisection steps (10 for the saturation rows).", ""]
        rows = [[c["A_close"], c["L_f"], _br(c["rbg"]), _br(c["solver"])] for c in P["checks"]["r6c"]]
        L += [C.md_table(rows, ["A_close (= A0)", "L_f", "reduced game", "full solver (R6c)"]), ""]
        rows = [[f"{c['A0']:.6g}", _br(c["rbg"]), fmt(c["closed_form"], 4)] for c in P["checks"]["saturation"]]
        L += [C.md_table(rows, ["A0 (saturated start)", "reduced game", "closed form (cap_gap_fail)"]), ""]
        L += ["## H2. Human preventive action, learning and tightening: outcomes (each measure separately)", ""]
        rows = []
        for s, R in P["measures"].items():
            for p, m in R.items():
                rr = P["raw"][s][p]
                rows.append([s, p, fmt(m["P_ai_strike"]), fmt(rr["strike_year"]), fmt(m["P_human_first"]),
                             fmt(rr["shutdown_year"]), fmt(m["P_warning_shot"]), fmt(rr["P_seizure"]),
                             fmt(m["successful_harm"]), fmt(m["control_retained"]), fmt(m["P_ai_eliminated"]),
                             fmt(m["V_H"], 4), fmt(m["V_A_excess"], 3)])
        L += [C.md_table(rows, ["structure", "policy", "P(AI strike)", "AI strike year", "P(human first strike)",
                                "human strike year", "P(a strike fails)", "P(seizure)", "successful harm",
                                "control retained", "P(AI eliminated)", "human welfare",
                                "AI value over solo growth"]), ""]
        L += _analysis_md("H3", P["analysis"])
    S = _load("selection")
    if S:
        L += ["## S1. Full solver: human-best versus human-worst stage-equilibrium selection (AS-SELECTION)", ""]
        rows = []
        for i, n in enumerate(S["names"]):
            rows.append([n, S["best"]["act0"][i], S["worst"]["act0"][i], fmt(S["best"]["att"][i]),
                         fmt(S["worst"]["att"][i]), fmt(S["best"]["riv"][i]), fmt(S["worst"]["riv"][i]),
                         fmt(S["best"]["WH"][i]), fmt(S["worst"]["WH"][i])])
        L += [C.md_table(rows, ["scenario", "AI move t0 (best)", "(worst)", "P(strike) best", "worst",
                                "P(rival) best", "worst", "human welfare best", "worst"]), "",
              "Scenarios whose opening move or strike class changes: " + (", ".join(S["flipped"]) or "none") + ".", ""]
    return "\n".join(L) + "\n"


def _br(b):
    return "none (strikes even at q = 1)" if b is None else f"[{b[0]:.4f}, {b[1]:.4f}]"


def _analysis_md(tag, A) -> list:
    L = [f"## {tag}. Ranking against `{A['reference']}`: reversals across structures and conflicts across measures", ""]
    rows = [[r["policy"], r["measure"], ", ".join(r["better_in"]), ", ".join(r["worse_in"])] for r in A["reversals"]]
    L += ["Reversals (better than the reference in some structures, worse in others):", "",
          C.md_table(rows, ["policy", "measure", "better in", "worse in"]) if rows else "none", ""]
    rows = [[c["policy"], c["structure"], ", ".join(c["better_on"]), ", ".join(c["worse_on"])] for c in A["conflicts"]]
    L += ["Conflicts (better on some measures, worse on others, in one structure):", "",
          C.md_table(rows, ["policy", "structure", "better on", "worse on"]) if rows else "none", ""]
    rows = [[p, s, d] for p, D in A["distribution"].items() for s, d in D.items()]
    L += ["Distribution against the reference (sign of the change in each side's value):", "",
          C.md_table(rows, ["policy", "structure", "change"]), ""]
    return L


def main(argv):
    stage = argv[1] if len(argv) > 1 else "default"
    t0 = time.time()
    if stage in ("default", "bargaining"):
        print("wrote", C.save_json("bargaining", stage_bargaining()))
    if stage in ("default", "preventive"):
        print("wrote", C.save_json("preventive", stage_preventive()))
    if stage == "selection":
        print("wrote", C.save_json("selection", stage_selection()))
    path = os.path.join(C.OUT, "tables.md")
    with open(path, "w") as f:
        f.write(render())
    print("wrote", path, f"({time.time() - t0:.0f} s)")


if __name__ == "__main__":
    main(sys.argv)
