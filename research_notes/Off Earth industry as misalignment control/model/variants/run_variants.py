"""Runner for the issue #9 variants. Run from model/:

    python3 variants/run_variants.py               # bargaining + preventive (about 30 s), then tables
    python3 variants/run_variants.py selection     # full solver, 25 named scenarios, sel best vs worst (about 10 min)
    python3 variants/run_variants.py tables        # re-render results/variants/tables.md from the JSON only

Writes results/variants/{bargaining,preventive,selection}.json and results/variants/tables.md. The write-up is
results/variants.md (hand-written from these tables). Nothing here edits equilibrium_model.py, robust_design.py or
ci_sims.py, and no committed baseline output is touched.
"""
